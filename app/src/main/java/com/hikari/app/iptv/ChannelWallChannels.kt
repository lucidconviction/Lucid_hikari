        all.filter { it.category.equals(category, ignoreCase = true) }

    /** The same matching rule as the reference page: short keywords are
     *  token boundaries, longer ones are plain contains, excluded words veto. */
    fun matches(streamName: String, keywords: List<String>, exclude: List<String> = emptyList()): Boolean {
        val lower = streamName.lowercase()
        if (exclude.any { lower.contains(it.lowercase()) }) return false
        for (raw in keywords) {
            val kw = raw.lowercase().trim()
            if (kw.isEmpty()) continue
            if (kw.length <= 3) {
                val regex = Regex("(?:^|[^a-zA-Z0-9])" + Regex.escape(kw) + "(?:$|[^a-zA-Z0-9])")
                if (regex.containsMatchIn(lower)) return true
            } else if (lower.contains(kw)) return true
        }
        return false
    }

    fun matches(channel: WallChannel, streamName: String): Boolean =
        matches(streamName, channel.keywords, channel.exclude)
